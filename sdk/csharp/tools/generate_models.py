# Server-only types mapped to something a client can hold.
TYPE_MAP = {
    "ServerSettings": "JsonObject",
    "IReadOnlyDictionary": "Dictionary",
    "IReadOnlyList": "List",
    "IList": "List",
    "ICollection": "List",
    "IEnumerable": "List",
    "IDictionary": "Dictionary",
}

# Types the SDK writes by hand; references are allowed but nothing is generated for them.
HAND_WRITTEN = {"EnumerationResult": "MyMorningNews.Sdk"}

SYSTEM_TYPES = {
    "string", "int", "long", "short", "byte", "double", "float", "decimal", "bool", "object", "char", "uint", "ulong",
    "DateTime", "DateTimeOffset", "TimeSpan", "Guid", "String", "Int32", "Int64", "Double", "Boolean",
}
COLLECTION_TYPES = {"List", "Dictionary", "HashSet", "SortedDictionary"}
JSON_TYPES = {"JsonObject": "System.Text.Json.Nodes", "JsonElement": "System.Text.Json", "JsonNode": "System.Text.Json.Nodes"}

CLASS_RE = re.compile(r"^\s*public\s+(?:sealed\s+|abstract\s+)*(class|enum)\s+(\w+)\s*(<[^>]+>)?\s*(?::\s*([^{]+))?\s*\{?\s*$")
PROP_RE = re.compile(r"^\s*public\s+(?!static\b|const\b|override\b|abstract\b|event\b|class\b|enum\b|delegate\b|readonly\b)"
                     r"(?:virtual\s+|new\s+|required\s+)*([A-Za-z_][\w<>\[\],\.\? ]*?)\s+([A-Z_]\w*)\s*(\{.*|=>.*|=.*;|;)?\s*$")
FIELD_RE = re.compile(r"^\s*private\s+(?:readonly\s+)?(?:static\s+)?[\w<>\[\],\.\? ]+?\s+_(\w+)\s*=\s*(.+);\s*$")
ENUM_MEMBER_RE = re.compile(r"^\s*([A-Z]\w*)\s*(?:=\s*([^,]+))?\s*,?\s*$")


def strip_strings(line):
    return re.sub(r'"(?:\\.|[^"\\])*"', '""', re.sub(r"'(?:\\.|[^'\\])'", "''", line))


def summary_of(doc_lines):
    text = " ".join(l.strip()[3:].strip() for l in doc_lines)
    m = re.search(r"<summary>(.*?)</summary>", text)
    s = m.group(1).strip() if m else ""
    s = re.sub(r'<see\s+cref="([^"]+)"\s*/>', lambda mm: mm.group(1).split(".")[-1], s)
    s = re.sub(r"\s+", " ", s).strip()
    s = s.replace("\u2014", ", ")
    s = s.replace("values outside the range are clamped", "the server clamps values outside the range")
    s = s.replace("Values outside the range are clamped", "The server clamps values outside the range")
    return s


class TypeInfo(object):
    def __init__(self, kind, name, namespace, source):
        self.kind = kind
        self.name = name
        self.namespace = namespace
        self.source = source
        self.summary = ""
        self.base = None
        self.props = []      # (type, name, initializer or None, summary)
        self.members = []    # (name, value or None, summary)
        self.fields = {}     # backing field defaults: Name -> expr


def parse_file(path, rel):
    types = []
    with open(path, "r", encoding="utf-8") as f:
        lines = f.read().splitlines()
    namespace = ""
    depth = 0
    doc = []
    stack = []  # (TypeInfo, body depth)
    pending = None
    for raw in lines:
        line = raw.rstrip()
        s = line.strip()
        if s.startswith("namespace "):
            namespace = s.split()[1].rstrip(";{")
        cur = stack[-1] if stack else None
        member_depth = cur[1] if cur else None
        if s.startswith("///"):
            doc.append(s)
        elif s.startswith("[") and s.endswith("]"):
            pass
        else:
            m = CLASS_RE.match(line)
            if m and (cur is None or depth == member_depth):
                t = TypeInfo(m.group(1), m.group(2), namespace, rel)
                t.summary = summary_of(doc)
                if m.group(3):
                    t.generic = m.group(3)
                else:
                    t.generic = None
                if m.group(4):
                    bases = [b.strip() for b in m.group(4).split(",")]
                    first = bases[0] if bases else ""
                    is_interface = len(first) > 1 and first[0] == "I" and first[1].isupper()
                    t.base = first if first and not is_interface else None
                types.append(t)
                pending = t
            elif cur is not None and depth == member_depth and s:
                t = cur[0]
                if t.kind == "enum":
                    em = ENUM_MEMBER_RE.match(s)
                    if em:
                        t.members.append((em.group(1), em.group(2), summary_of(doc)))
                else:
                    fm = FIELD_RE.match(line)
                    pm = PROP_RE.match(line) if not fm else None
                    if fm:
                        t.fields[fm.group(1)] = fm.group(2).strip()
                    elif pm and "(" not in pm.group(1) and not re.match(r"^\s*public\s+" + re.escape(t.name) + r"\s*\(", line):
                        rest = pm.group(3) or ""
                        if "(" in line.split(pm.group(2), 1)[1].split("{")[0].split("=")[0]:
                            pass  # method
                        else:
                            init = None
                            im = re.search(r"\}\s*=\s*(.+);\s*$", rest)
                            if im:
                                init = im.group(1).strip()
                            t.props.append([pm.group(1).strip(), pm.group(2), init, summary_of(doc)])
            doc = []
        clean = strip_strings(line)
        # Ignore braces inside // comments.
        if "//" in clean:
            clean = clean.split("//", 1)[0]
        opens = clean.count("{")
        closes = clean.count("}")
        if pending is not None and opens > 0:
            stack.append((pending, depth + 1))
            pending = None
        depth += opens - closes
        while stack and depth < stack[-1][1]:
            stack.pop()
    return types


def scan(core):
    found = {}
    dupes = {}
    for root, dirs, files in os.walk(core):
        dirs[:] = [d for d in dirs if d not in ("bin", "obj", "Database")]
        for fn in files:
            if not fn.endswith(".cs"):
                continue
            path = os.path.join(root, fn)
            rel = os.path.relpath(path, os.path.dirname(os.path.dirname(core)))
            for t in parse_file(path, rel):
                if t.name in found:
                    dupes.setdefault(t.name, [found[t.name].source]).append(t.source)
                    continue
                found[t.name] = t
    return found, dupes


def identifiers(type_str):
    return re.findall(r"[A-Za-z_]\w*", type_str)


def map_type(type_str):
    # Drop namespace qualifiers (Models.Feedback, MyMorningNews.Core.Models.Feedback, System.Text.Json.JsonElement).
    out = re.sub(r"\b(?:[A-Za-z_]\w*\.)+([A-Za-z_]\w*)", r"\1", type_str)
    for k, v in TYPE_MAP.items():
        out = re.sub(r"\b" + k + r"\b", v, out)
    return out


def closure(found):
    keep = []
    seen = set()
    queue = list(ROOTS)
    missing = []
    while queue:
        n = queue.pop(0)
        if n in seen:
            continue
        seen.add(n)
        if n in HAND_WRITTEN or n in TYPE_MAP or n in SYSTEM_TYPES or n in COLLECTION_TYPES or n in JSON_TYPES:
            continue
        t = found.get(n)
        if t is None:
            missing.append(n)
            continue
        keep.append(t)
        if t.base and t.base in found:
            queue.append(t.base)
        for p in t.props:
            for ident in identifiers(map_type(p[0])):
                if ident not in seen:
                    queue.append(ident)
    return keep, missing


def target_namespace(t):
    if t.kind == "enum":
        return "MyMorningNews.Sdk.Enums"
    if t.namespace.endswith(".Requests"):
        return "MyMorningNews.Sdk.Requests"
    return "MyMorningNews.Sdk.Models"


def folder_of(ns):
    return ns.split(".")[-1]


SAFE_LITERAL = re.compile(r'^(-?\d+(\.\d+)?[mMdDfFlL]?|true|false|null|"(?:\\.|[^"\\])*"|String\.Empty|string\.Empty|DateTime\.MinValue|TimeSpan\.Zero)$')


def safe_initializer(init, ptype, emitted):
    if init is None:
        return None
    init = init.strip()
    if SAFE_LITERAL.match(init):
        return init
    m = re.match(r"^(\w+)\.(\w+)$", init)
    if m and m.group(1) in emitted and emitted[m.group(1)].kind == "enum":
        return init
    m = re.match(r"^new\s+([\w<>, \[\]\.\?]+?)\s*\((.*)\)$", init)
    if m:
        ctor = map_type(m.group(1))
        args = m.group(2).strip()
        idents = [i for i in identifiers(ctor) if i not in SYSTEM_TYPES and i not in COLLECTION_TYPES and i not in JSON_TYPES and i not in emitted and i not in HAND_WRITTEN]
        if idents:
            return None
        if args and not re.match(r"^StringComparer\.\w+$", args):
            return None
        return "new " + ctor + "(" + args + ")"
    if init in ("new()",):
        return None
    return None


def fallback_initializer(ptype, emitted):
    t = ptype.strip()
    if t.endswith("?"):
        return None
    base = re.match(r"^(\w+)", t)
    name = base.group(1) if base else t
    if t in ("string", "String"):
        return "String.Empty"
    if t.endswith("[]"):
        return "Array.Empty<" + t[:-2] + ">()"
    if name in COLLECTION_TYPES:
        return "new " + t + "()"
    if name in JSON_TYPES and name != "JsonElement":
        return "new " + t + "()"
    if name in emitted and emitted[name].kind == "class":
        return "new " + t + "()"
    if name in HAND_WRITTEN:
        return "new " + t + "()"
    return None


def wrap_doc(text, indent):
    if not text:
        text = "No description."
    if not text.endswith((".", "?", "!", ")")):
        text += "."
    return [indent + "/// <summary>", indent + "/// " + text, indent + "/// </summary>"]


def render_enum(t):
    ns = target_namespace(t)
    out = ["namespace " + ns, "{", "    " + MARKER, "    // Source: " + t.source.replace(os.sep, "/"), ""]
    out += wrap_doc(t.summary, "    ")
    out.append("    public enum " + t.name)
    out.append("    {")
    for i, (name, value, summ) in enumerate(t.members):
        out += wrap_doc(summ, "        ")
        line = "        " + name + ((" = " + value.strip()) if value else "")
        if i < len(t.members) - 1:
            line += ","
        out.append(line)
        if i < len(t.members) - 1:
            out.append("")
    out.append("    }")
    out.append("}")
    return "\n".join(out) + "\n"


def render_class(t, emitted):
    ns = target_namespace(t)
    usings = set()
    body = []
    for ptype, pname, init, summ in t.props:
        mtype = map_type(ptype)
        # Non-nullable value or reference type: keep a safe default or pick one.
        default = safe_initializer(init, mtype, emitted)
        if default is None and init is None and pname in t.fields:
            default = safe_initializer(t.fields[pname], mtype, emitted)
        if default is None:
            default = fallback_initializer(mtype, emitted)
        if mtype.strip() == "object":
            mtype = "object?"
        for ident in identifiers(mtype + " " + (default or "")):
            if ident in ("DateTime", "DateTimeOffset", "TimeSpan", "Guid", "String", "StringComparer", "Array"):
                usings.add("System")
            elif ident in COLLECTION_TYPES:
                usings.add("System.Collections.Generic")
            elif ident in JSON_TYPES:
                usings.add(JSON_TYPES[ident])
            elif ident in HAND_WRITTEN:
                if HAND_WRITTEN[ident] != ns:
                    usings.add(HAND_WRITTEN[ident])
            elif ident in emitted:
                other = target_namespace(emitted[ident])
                if other != ns:
                    usings.add(other)
        doc = summ
        if default is not None and default not in ("String.Empty", "null") and not default.startswith("new ") and not default.startswith("Array."):
            shown = default.split(".")[-1] if re.match(r"^\w+\.\w+$", default) else default
            if "Default" not in doc and "default" not in doc:
                doc = (doc.rstrip(".") + ". " if doc else "") + "Default " + shown + "."
        body += wrap_doc(doc, "        ")
        body.append("        public " + mtype + " " + pname + " { get; set; }" + ((" = " + default + ";") if default is not None else ""))
        body.append("")
    if body:
        body.pop()
    base = ""
    if t.base and t.base in emitted:
        base = " : " + t.base
        other = target_namespace(emitted[t.base])
        if other != ns:
            usings.add(other)
    system = sorted(u for u in usings if u.startswith("System") or u.startswith("Microsoft"))
    rest = sorted(u for u in usings if not (u.startswith("System") or u.startswith("Microsoft")))
    out = ["namespace " + ns, "{", "    " + MARKER, "    // Source: " + t.source.replace(os.sep, "/")]
    if system or rest:
        out.append("")
    for u in system + rest:
        out.append("    using " + u + ";")
    out.append("")
    out += wrap_doc(t.summary, "    ")
    out.append("    public class " + t.name + base)
    out.append("    {")
    out += body
    if body:
        out.append("")
    out += wrap_doc("Instantiate.", "        ")
    out.append("        public " + t.name + "()")
    out.append("        {")
    out.append("        }")
    out.append("    }")
    out.append("}")
    return "\n".join(out) + "\n"


def is_generated(path):
    try:
        with open(path, "r", encoding="utf-8") as f:
            head = f.read(400)
        return MARKER in head
    except OSError:
        return False


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    repo = os.path.abspath(os.path.join(here, "..", "..", ".."))
    ap = argparse.ArgumentParser(description="Generate SDK models from MyMorningNews.Core.")
    ap.add_argument("--core", default=os.path.join(repo, "src", "MyMorningNews.Core"))
    ap.add_argument("--out", default=os.path.join(repo, "sdk", "csharp", "MyMorningNews.Sdk"))
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    found, dupes = scan(args.core)
    keep, missing = closure(found)
    emitted = {t.name: t for t in keep}
    problems = [d for d in dupes if d in emitted]
    if problems:
        for d in problems:
            print("error: type name " + d + " is declared more than once: " + ", ".join(dupes[d]), file=sys.stderr)
        return 2
    unknown = [m for m in missing if not m[0].islower()]
    if unknown:
        print("note: referenced but not generated (system or unknown): " + ", ".join(sorted(set(unknown))), file=sys.stderr)

    written = set()
    changed = 0
    for t in sorted(keep, key=lambda x: x.name):
        if getattr(t, "generic", None):
            print("skip generic " + t.name, file=sys.stderr)
            continue
        ns = target_namespace(t)
        folder = os.path.join(args.out, folder_of(ns))
        path = os.path.join(folder, t.name + ".cs")
        text = render_enum(t) if t.kind == "enum" else render_class(t, emitted)
        written.add(os.path.abspath(path))
        old = None
        if os.path.exists(path):
            if not is_generated(path):
                print("skip hand-written " + path, file=sys.stderr)
                continue
            with open(path, "r", encoding="utf-8") as f:
                old = f.read()
        if old != text:
            changed += 1
            if not args.check:
                os.makedirs(folder, exist_ok=True)
                with open(path, "w", encoding="utf-8", newline="\n") as f:
                    f.write(text)
    removed = 0
    for sub in ("Models", "Requests", "Enums"):
        folder = os.path.join(args.out, sub)
        if not os.path.isdir(folder):
            continue
        for fn in os.listdir(folder):
            p = os.path.abspath(os.path.join(folder, fn))
            if fn.endswith(".cs") and p not in written and is_generated(p):
                removed += 1
                if not args.check:
                    os.remove(p)
    kinds = {"Models": 0, "Requests": 0, "Enums": 0}
    for t in keep:
        kinds[folder_of(target_namespace(t))] += 1
    print("types: " + ", ".join(k + "=" + str(v) for k, v in kinds.items()) + "; changed " + str(changed) + "; removed " + str(removed) + (" (check only)" if args.check else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
